"""Отклик на имя «Джарвис» во время активной сессии.

Раньше: если сессия уже открыта (session_active=True) и пользователь
снова говорит «Джарвис», wake.listen() не вызывается, Vosk распознаёт
слово, роутер не находит плагина — выдаёт «не знаю такой команды».

Теперь: плагин перехватывает «джарвис» / «джарвис ...» и отвечает
случайной фразой из LISTENING (та же логика, что при первом wake-word).
"""

from core.phrases import LISTENING, random_phrase

PRIORITY = 90   # очень высокий — чтобы перехватить раньше других

PHRASES = [
    "джарвис",
    "джарвис,",
    "джарвис!",
    "джарвис?",
    "эй джарвис",
    "эй, джарвис",
    "слушай джарвис",
    "окей джарвис",
    "ок джарвис",
    "jarvis",
    "hey jarvis",
    "ok jarvis",
]


def match(text):
    """Срабатывает, если фраза — это обращение к Джарвису.

    Работает только для коротких фраз: «джарвис», «эй джарвис», «ок джарвис».
    Не срабатывает на «джарвис перезапусти себя» (это команда для других плагинов).
    """
    if not text:
        return False

    t = text.strip().lower().strip(".,!?")

    # точное совпадение с одной из фраз
    for p in PHRASES:
        if t == p.strip(".,!?"):
            return True

    # фраза состоит ТОЛЬКО из «джарвис» и служебных слов (без команд)
    words = t.replace(",", " ").replace("!", " ").replace("?", " ").split()
    if not words:
        return False

    # должно быть слово "джарвис" или "jarvis"
    if "джарвис" not in words and "jarvis" not in words:
        return False

    # и больше в фразе не должно быть командных слов
    command_words = {
        "открой", "закрой", "запусти", "включи", "выключи",
        "перезапусти", "перезагрузись", "рестарт", "restart",
        "найди", "поищи", "скажи", "покажи", "смени", "поставь",
        "обнови", "проверь", "установи", "переведи", "напиши",
        "громче", "тише", "пауза", "продолжи", "следующий", "предыдущий",
        "таймер", "будильник", "секундомер", "погода", "время",
    }
    if any(w in command_words for w in words):
        return False

    return True


def run(jarvis, text):
    # Просто откликаемся той же фразой, что и при первом wake-word
    jarvis.say_async(random_phrase(LISTENING))
    return True